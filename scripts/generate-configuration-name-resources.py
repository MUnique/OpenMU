#!/usr/bin/env python3
"""Regenerate typed configuration-name resource accessors from the neutral resx files."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'src/Persistence/Initialization/Properties'
CATEGORIES = ('CharacterClassNames', 'MapNames', 'MerchantNames', 'MonsterNames')
for category in CATEGORIES:
    entries = ET.parse(DIRECTORY / f'{category}.resx').getroot().findall('data')
    properties = '\n'.join(
        f'    /// <summary>Gets the localized {entry.attrib["name"]} name.</summary>\n'
        f'    public static string {entry.attrib["name"]} => ResourceManager.GetString(nameof({entry.attrib["name"]}), Culture)!;\n'
        for entry in entries
    )
    output = f'''// <auto-generated />
#nullable enable
namespace MUnique.OpenMU.Persistence.Initialization.Properties;

using System.Globalization;
using System.Resources;

/// <summary>Strongly typed {category} resources.</summary>
public static class {category}
{{
    /// <summary>Gets the resource manager.</summary>
    public static ResourceManager ResourceManager {{ get; }} = new("MUnique.OpenMU.Persistence.Initialization.Properties.{category}", typeof({category}).Assembly);

    /// <summary>Gets or sets the culture used by the string accessors.</summary>
    public static CultureInfo? Culture {{ get; set; }}

{properties}}}
'''
    (DIRECTORY / f'{category}.Designer.cs').write_text(output)

# Regenerate this feature's plugin properties using the existing designer's expression-bodied style.
designer = DIRECTORY / 'PlugInResources.Designer.cs'
text = designer.read_text(encoding='utf-8-sig')
text = re.sub(
    r'        /// <summary>Gets the localized (?:AddMissingChineseConfigurationNames|AddConfigurationNameTranslations)_(?:Name|Description) text.</summary>\n'
    r'        public static string [^\n]+\n\n', '', text
)
properties = ''
for entry in ET.parse(DIRECTORY / 'PlugInResources.resx').getroot().findall('data'):
    key = entry.attrib['name']
    if key.startswith('AddConfigurationNameTranslations_'):
        properties += (f'        /// <summary>Gets the localized {key} text.</summary>\n'
                       f'        public static string {key} => ResourceManager.GetString("{key}", resourceCulture)!;\n\n')
index = text.rfind('    }')
designer.write_text(text[:index] + properties + text[index:], encoding='utf-8-sig')
