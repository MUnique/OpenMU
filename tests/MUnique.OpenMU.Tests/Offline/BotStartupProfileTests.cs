namespace MUnique.OpenMU.Tests.Offline;

using MUnique.OpenMU.GameLogic.Bots;

/// <summary>
/// Tests for the two <see cref="BotStartupProfile"/> kinds and their factory.
/// </summary>
[TestFixture]
public class BotStartupProfileTests
{
    /// <summary>
    /// Tests that the fresh profile always generates a level-1 character with level-0 starter gear and
    /// no reset history, regardless of the veteran level bounds or the configured reset seeding.
    /// </summary>
    [Test]
    public void FreshProfile_AlwaysStartsAtLevelOne()
    {
        var profile = BotStartupProfile.For(true);

        var level = profile.GetStartLevel(10, 250);
        var resets = profile.GetSeededResets(100);

        Assert.Multiple(() =>
        {
            Assert.That(level, Is.EqualTo(1));
            Assert.That(profile.StarterItemLevel, Is.EqualTo(0));
            Assert.That(resets, Is.EqualTo(0));
            Assert.That(profile.MinLevel, Is.EqualTo(1));
            Assert.That(profile.MaxLevel, Is.EqualTo(1));
        });
    }

    /// <summary>
    /// Tests that the veteran profile rolls a level within the given bounds and keeps the +6 starter gear.
    /// </summary>
    [Test]
    public void VeteranProfile_LevelStaysWithinBounds()
    {
        var profile = BotStartupProfile.For(false);

        var level = profile.GetStartLevel(10, 250);

        Assert.Multiple(() =>
        {
            Assert.That(level, Is.InRange(10, 250));
            Assert.That(profile.StarterItemLevel, Is.EqualTo(6));
        });
    }

    /// <summary>
    /// Tests that the veteran profile seeds only as many resets as configured - none when disabled.
    /// </summary>
    [Test]
    public void VeteranProfile_SeedsResetsOnlyWhenConfigured()
    {
        var profile = BotStartupProfile.For(false);

        var resets = profile.GetSeededResets(5);

        Assert.That(resets, Is.InRange(0, 5));
        Assert.That(profile.GetSeededResets(0), Is.EqualTo(0));
    }

    /// <summary>
    /// Tests that a fresh bot generated by the profile maps back to the fresh profile, so the generator
    /// really does not branch on the flag itself.
    /// </summary>
    [Test]
    public void FreshProfile_IsDeterministic()
    {
        var profile = BotStartupProfile.For(true);

        Assert.That(profile.GetStartLevel(1, 1), Is.EqualTo(1));
        Assert.That(profile.GetStartLevel(1, 1), Is.EqualTo(1));
    }
}